# -*- coding: utf-8 -*-
"""Проверки самого бенчмарка: разрезка на предложения и сравнение с эталоном.

Запуск: python _diag/bench/test_bench.py
Без этих проверок замер врёт тихо: неверная разрезка сместит предложения, а
неверное сравнение покажет «100 %» там, где движок вообще не отвечал.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bench import apply_answers, classify  # noqa: E402
from sentences import split_sentences  # noqa: E402

A = "\u0301"
failed = 0


def check(name, actual, expected):
    global failed
    ok = actual == expected
    failed += 0 if ok else 1
    print(("OK   " if ok else "FAIL ") + name)
    if not ok:
        print("   получено:", actual)
        print("   ожидалось:", expected)


# --- разрезка -------------------------------------------------------------
check("две фразы", split_sentences("Упал снег. Утро было тихое."),
      ["Упал снег.", "Утро было тихое."])
check("сокращение т. е.", split_sentences("Он писал, т. е. не разговаривал. Потом ушёл."),
      ["Он писал, т. е. не разговаривал.", "Потом ушёл."])
check("инициалы", split_sentences("Это сделал М. А. Шолохов. Он уехал."),
      ["Это сделал М. А. Шолохов.", "Он уехал."])
check("кавычка после точки", split_sentences("Он сказал: «Иди домой.» Мать молчала."),
      ["Он сказал: «Иди домой.»", "Мать молчала."])
check("многоточие в реплике", split_sentences("— Ну… — протянул он. — Ладно."),
      ["— Ну… — протянул он.", "— Ладно."])
check("без знака в конце", split_sentences("Незаконченная фраза"), ["Незаконченная фраза"])
check("пустой", split_sentences("   "), [])

# --- ответ разметчика -----------------------------------------------------
# Формат ответа — по НОМЕРАМ слов: "1=2 4=2" — первое и четвертое слово, 2-я гласная.
check("ударение по номеру слова", apply_answers("мала девочка", "1=2"),
      "мала" + A + " девочка")
check("два слова", apply_answers("от мала до велика", "2=2 4=3"),
      "от мала" + A + " до велика" + A)
check("2-я гласная у последнего слова не третья", apply_answers("велика", "1=2"),
      "вели" + A + "ка")
check("номер вне текста игнорируется", apply_answers("мала девочка", "9=1"),
      "мала девочка")
check("третья гласная", apply_answers("велика", "1=3"), "велика" + A)

# --- сравнение ------------------------------------------------------------
check("всё верно", classify("от мала" + A + " до велика" + A,
                            "от мала" + A + " до велика" + A), [])
check("идиома, ошибка модели", sorted({kind for _, kind, _, _ in classify(
    "от мала" + A + " до велика" + A, "от ма" + A + "ла до вели" + A + "ка")}),
    ["идиома"])
# Здесь ошибка только в «мала», «велика» верно: «идиома» должна пометить оба слова
# пары, иначе ошибка в одном слове фразы не отличима от обычной.
check("идиома, одно слово", [kind for _, kind, _, _ in classify(
    "от мала" + A + " до велика" + A, "от ма" + A + "ла до велика" + A)],
    ["идиома"])
check("обычная ошибка ударения", [kind for _, kind, _, _ in classify(
    "кни" + A + "га", "книга" + A)], ["ударение"])
check("ё против е", [kind for _, kind, _, _ in classify(
    "всё прошло", "все" + A + " прошло")], ["ё"])
check("сдвиг слов", [kind for _, kind, _, _ in classify(
    "два слова", "три слова тут")], ["сдвиг"])

print("\nитог:", "всё прошло" if failed == 0 else f"провалов {failed}")
sys.exit(1 if failed else 0)
